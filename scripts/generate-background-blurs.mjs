// Writes src/data/backgroundBlur.ts: a tiny blurred copy of every hero plate,
// inlined into the page so a background shows the moment the page does and
// sharpens when the full image arrives. Run after changing /public/backgrounds:
//   node scripts/generate-background-blurs.mjs
import { readdirSync, writeFileSync } from "node:fs";
import path from "node:path";
import sharp from "sharp";

const dir = path.resolve("public/backgrounds");
const plates = readdirSync(dir).filter((f) => /^(dark|light)-hero-\d+\.jpg$/.test(f)).sort();

const lines = [];
for (const file of plates) {
  const buf = await sharp(path.join(dir, file)).resize(32).webp({ quality: 50 }).toBuffer();
  lines.push(`  "${file.replace(/\.jpg$/, "")}": "data:image/webp;base64,${buf.toString("base64")}",`);
}

writeFileSync(
  path.resolve("src/data/backgroundBlur.ts"),
  `// Generated by scripts/generate-background-blurs.mjs — do not edit by hand.\n` +
    `export const BACKGROUND_BLUR: Record<string, string> = {\n${lines.join("\n")}\n};\n`,
);
console.log(`wrote ${plates.length} previews`);
